"""Publish docs/api/openapi.json on the website.

Writes <out>/api/openapi.json (with $refs pointing to the copied schemas),
<out>/api/schemas/*.json (the official DSP JSON Schemas from the
repository) and <out>/api/index.html, a plain list of the endpoints that
loads nothing from other sites.

Usage: openapi_site.py docs/api/openapi.json crates/ldsc-dsp/tests/schemas _site
All paths must lie inside the working directory (the repository root).
"""
import html
import json
import shutil
import sys
from pathlib import Path

PREFIX = "../../crates/ldsc-dsp/tests/schemas/"


def rewrite(node, used):
    """Point every $ref at schemas/<file>; collect the files used."""
    if isinstance(node, dict):
        out = {}
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str) and value.startswith(PREFIX):
                name = value[len(PREFIX):]
                if "/" in name or not name.endswith(".json"):
                    raise ValueError(f"unexpected $ref {value}")
                used.add(name)
                out[key] = "schemas/" + name
            else:
                out[key] = rewrite(value, used)
        return out
    if isinstance(node, list):
        return [rewrite(v, used) for v in node]
    return node


def page(spec):
    esc = html.escape
    rows = []
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            codes = ", ".join(sorted(op.get("responses", {})))
            rows.append(
                f"<tr><td><code>{esc(method.upper())}</code></td><td><code>{esc(path)}</code></td>"
                f"<td>{esc(op.get('summary', ''))}</td><td>{esc(codes)}</td></tr>"
            )
    info = spec["info"]
    return f"""<!doctype html>
<!-- SPDX-FileCopyrightText: LDSC contributors -->
<!-- SPDX-License-Identifier: Apache-2.0 -->
<!-- Generated by scripts/openapi_site.py from docs/api/openapi.json. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>LDSC HTTP interface</title>
  <meta name="color-scheme" content="light dark">
  <link rel="icon" href="../favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="../style.css">
</head>
<body>
  <main id="main">
    <section>
      <div class="wrap">
        <p><a href="../">LDSC</a></p>
        <h1>{esc(info['title'])} HTTP interface</h1>
        <p>{esc(info.get('description', ''))}</p>
        <p>Machine-readable: <a href="openapi.json">openapi.json</a> (OpenAPI {esc(spec['openapi'])}),
        with the official DSP JSON Schemas next to it. Open it in any OpenAPI viewer.</p>
        <table>
          <thead><tr><th>Method</th><th>Path</th><th>What it does</th><th>Responses</th></tr></thead>
          <tbody>
            {"".join(rows)}
          </tbody>
        </table>
      </div>
    </section>
  </main>
</body>
</html>
"""


def inside_workdir(path: str) -> Path:
    """The path resolved inside the working directory; refuses anything else."""
    root = Path.cwd().resolve()
    resolved = (root / path).resolve()
    if not resolved.is_relative_to(root):
        raise ValueError(f"refusing {path}: not inside the working directory")
    return resolved


def main(spec_arg, schema_arg, out_arg):
    spec_path = inside_workdir(spec_arg)
    schema_dir = inside_workdir(schema_arg)
    out_dir = inside_workdir(out_arg)
    spec = json.loads(spec_path.read_text(encoding="utf-8"))
    used = set()
    published = rewrite(spec, used)
    api = out_dir / "api"
    (api / "schemas").mkdir(parents=True, exist_ok=True)
    for name in sorted(used):
        shutil.copyfile(schema_dir / name, api / "schemas" / name)
    (api / "openapi.json").write_text(json.dumps(published, indent=2) + "\n", encoding="utf-8")
    (api / "index.html").write_text(page(spec), encoding="utf-8")
    print(f"published {len(used)} schemas and {sum(len(o) for o in spec['paths'].values())} operations")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 4:
        print(__doc__)
        sys.exit(2)
    sys.exit(main(*sys.argv[1:]))
